class ThemePalette {
  final String id;
  final String name;
  final List<String> preview;
  final Map<String, String> colors;

  const ThemePalette({
    required this.id,
    required this.name,
    required this.preview,
    required this.colors,
  });

  MenuPublicoTheme toMenuTheme() =>
      MenuPublicoTheme.fromJson({'colors': colors});
}

